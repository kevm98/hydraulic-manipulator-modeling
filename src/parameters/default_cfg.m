function C = default_cfg(likeT,TINI,NPRED,HMAX,HCAP) %#codegen %#ok<INUSD>
Ts = cast(0.005,'like',likeT);

vc = cast([8;8;6;6;10],'like',likeT);
k1 = vc.^2;  k2 = 2.*vc;
vo = cast([60;60;50;50;80],'like',likeT);

b0_nom = cast(1.0*ones(5,1),'like',likeT);
sgn_b0 = cast(ones(5,1),'like',likeT);

E_blf        = cast(0.5*ones(5,1),'like',likeT);
db_width_nom = cast(0.06*ones(5,1),'like',likeT);
db_hyst      = cast(0.015*ones(5,1),'like',likeT);

alpha1 = cast(0.5,'like',likeT);
alpha2 = cast(0.25,'like',likeT);
alpha3 = cast(0.10,'like',likeT);
deltaN = cast(5e-4,'like',likeT);

f_vlp  = cast([40;40;35;35;45],'like',likeT);

Ps_min = cast(2e6,'like',likeT);
Ps_max = cast(35e6,'like',likeT);
F_sum_max = cast(4*20000,'like',likeT);

lam_y_p = cast(5.0,'like',likeT);
lam_y_f = cast(2.0,'like',likeT);
lam_g   = cast(1e-2,'like',likeT);
lam_u   = cast(5.0,'like',likeT);
lam_s   = cast(1e3,'like',likeT);
deepc_stride = int32(2);
ymin = -pi/2*ones(5,1,'like',likeT);
ymax =  pi/2*ones(5,1,'like',likeT);
ctx_sigma_ps = cast(0.15,'like',likeT);
ctx_sigma_f  = cast(0.20,'like',likeT);

osqp_settings = struct( ...
    'rho',      cast(0.1,'like',likeT), ...
    'sigma',    cast(1e-6,'like',likeT), ...
    'alpha',    cast(1.6,'like',likeT), ...
    'max_iter', int32(600), ...
    'eps_abs',  cast(1e-4,'like',likeT), ...
    'eps_rel',  cast(1e-4,'like',likeT), ...
    'verbose',  false, ...
    'polish',   true );

scale_eps      = cast(1e-3,'like',likeT);
scale_update_N = int32(200);
outlier_jump   = cast(0.5,'like',likeT);
umax_rate      = cast(0.12,'like',likeT);

C = struct( ...
  'Ts',Ts, ...
  'vc',vc,'k1',k1,'k2',k2, ...
  'vo',vo, ...
  'b0_nom',b0_nom,'sgn_b0',sgn_b0, ...
  'E_blf',E_blf,'db_width_nom',db_width_nom,'db_hyst',db_hyst, ...
  'alpha1',alpha1,'alpha2',alpha2,'alpha3',alpha3,'deltaN',deltaN, ...
  'f_vlp',f_vlp, ...
  'Ps_min',Ps_min,'Ps_max',Ps_max,'F_sum_max',F_sum_max, ...
  'HMAX',double(HMAX),'Tini',double(TINI),'Npred',int32(NPRED), ...
  'lam_y_p',lam_y_p,'lam_y_f',lam_y_f,'lam_g',lam_g,'lam_u',lam_u,'lam_s',lam_s, ...
  'deepc_stride',deepc_stride, ...
  'ymin',ymin,'ymax',ymax, ...
  'ctx_sigma_ps',ctx_sigma_ps,'ctx_sigma_f',ctx_sigma_f, ...
  'osqp_settings',osqp_settings, ...
  'scale_eps',scale_eps,'scale_update_N',scale_update_N,'outlier_jump',outlier_jump, ...
  'umax_rate',umax_rate );
end
